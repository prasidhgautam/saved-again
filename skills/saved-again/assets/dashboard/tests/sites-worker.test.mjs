import assert from "node:assert/strict";
import { access } from "node:fs/promises";
import test from "node:test";
import worker, { safeSyncItem } from "../worker/index.js";

test("serves existing static assets without a fallback", async () => {
  const calls = [];
  const response = await worker.fetch(new Request("https://example.test/assets/app.js"), {
    ASSETS: {
      fetch: async (request) => {
        calls.push(new URL(request.url).pathname);
        return new Response("asset", { status: 200 });
      },
    },
  });

  assert.equal(response.status, 200);
  assert.deepEqual(calls, ["/assets/app.js"]);
});

test("falls back to index.html for an unknown app route", async () => {
  const calls = [];
  const response = await worker.fetch(
    new Request("https://example.test/flow/step-two?source=share", {
      headers: { accept: "text/html" },
    }),
    {
      ASSETS: {
        fetch: async (request) => {
          const url = new URL(request.url);
          calls.push(url.pathname + url.search);
          return new Response(url.pathname === "/index.html" ? "app" : "missing", {
            status: url.pathname === "/index.html" ? 200 : 404,
          });
        },
      },
    },
  );

  assert.equal(response.status, 200);
  assert.deepEqual(calls, ["/flow/step-two?source=share", "/index.html"]);
});

test("does not turn missing API or write requests into the app shell", async () => {
  for (const [request, expectedAssetCalls] of [
    [new Request("https://example.test/api/missing", { headers: { accept: "application/json" } }), 0],
    [new Request("https://example.test/flow", { method: "POST", headers: { accept: "text/html" } }), 1],
  ]) {
    let calls = 0;
    const response = await worker.fetch(request, {
      TEST_BYPASS_ACCESS: "true",
      ASSETS: {
        fetch: async () => {
          calls += 1;
          return new Response("missing", { status: 404 });
        },
      },
    });

    assert.equal(response.status, 404);
    assert.equal(calls, expectedAssetCalls);
  }
});

test("cloud APIs require Access and reject private analysis fields", async () => {
  const response = await worker.fetch(new Request("https://example.test/api/capabilities"), {});
  assert.equal(response.status, 401);
  assert.throws(() => safeSyncItem({ id: "Synthetic001", transcript: "private" }), /Private analysis/);
  assert.throws(() => safeSyncItem({ id: "Synthetic001", embeddings: [0.1] }), /Private analysis/);
  assert.deepEqual(safeSyncItem({ id: "Synthetic001", title: "Safe summary", summary: "Useful" }), {
    id: "Synthetic001",
    title: "Safe summary",
    summary: "Useful",
  });
});

